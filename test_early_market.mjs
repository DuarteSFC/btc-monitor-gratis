import assert from "node:assert/strict";
import {attentionAt,attentionEvents,chooseAttention} from "./early_market.mjs";
const now=Date.UTC(2026,0,1),ms=60000;
const base=Array.from({length:60},(_,i)=>({t:now-(60-i)*ms,o:60000,h:60010,l:59990,c:60000,v:10}));
const patch=p=>[...base.slice(0,-1),{...base.at(-1),...p}];
const spike=patch({o:60000,h:60032,l:59999,c:60030,v:50});
const e=attentionAt(spike,"mock",now);
assert.equal(e.pattern,"volume_acceleration");
assert.equal(e.classification,"observed_market_attention_not_entry");
assert.equal(e.volumeVs20,5);
assert.equal(attentionAt(patch({o:60000,h:60032,l:59999,c:60030,v:12}),"mock",now),null);
assert.equal(attentionAt(patch({o:60000,h:60003,l:59999,c:60001,v:100}),"mock",now),null);
assert.equal(attentionAt(patch({o:60000,h:60001,l:59960,c:59965,v:80}),"mock",now),null);
assert.equal(attentionAt(spike,"mock",now-1),null);
assert.equal(attentionAt(spike.filter((_,i)=>i!==58),"mock",now),null);
assert.equal(attentionAt(patch({v:-1}),"mock",now),null);
const seq=base.map((z,i)=>i===57?{...z,o:60000,c:60013,h:60015,v:17}:i===58?{...z,o:60013,c:60025,h:60027,l:60012,v:17}:i===59?{...z,o:60025,c:60045,h:60046,l:60024,v:17}:z);
assert.equal(attentionAt(seq,"mock",now).pattern,"three_minute_acceleration");
assert.equal(attentionEvents(spike,"mock",now).length,1);
assert.equal(chooseAttention([e],[],new Set(),0,now).length,1);
assert.equal(chooseAttention([e],[],new Set([e.id]),0,now).length,0);
assert.equal(chooseAttention([e],[],new Set(),now-60000,now).length,0);
assert.equal(chooseAttention([e],[{type:"breakout",closedUtc:e.closedUtc}],new Set(),0,now).length,0);
assert.equal(chooseAttention([e],[{type:"support_loss",closedUtc:e.closedUtc}],new Set(),0,now).length,1);
assert.equal(chooseAttention([e],[],new Set(),0,now+600001).length,0);
console.log("OK: 1M factual acceleration, three-minute burst, direction, volume, continuity, freshness, dedup and baseline preservation.");
